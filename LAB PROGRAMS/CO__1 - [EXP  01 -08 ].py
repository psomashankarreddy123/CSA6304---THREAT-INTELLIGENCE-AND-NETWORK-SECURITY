"""**4. Demonstrate VPN Tunnel Confidentiality Using a Symmetric Stream Cipher**"""

def xor_cipher(data, key):
    return bytes(
        byte ^ key[i % len(key)]
        for i, byte in enumerate(data)
    )


message = input("Enter message to send: ").encode()
key = input("Enter shared key: ").encode()

if not key:
    print("Error: Key cannot be empty.")
