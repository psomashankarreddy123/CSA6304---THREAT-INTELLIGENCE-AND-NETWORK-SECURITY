detect_phishing(url)

"""**7. Simulate the Three ELK Stack Roles Using Python**"""

import re
from collections import Counter

# Raw logs: timestamp, level, and message
raw_logs = [
    "2026-10-16 10:00:00 INFO User logged in",
    "2026-10-16 10:01:00 ERROR Login failed",
    "2026-10-16 10:02:00 WARNING Multiple login attempts",
    "2026-10-16 10:03:00 ERROR Access denied",
    "2026-10-16 10:04:00 INFO Session closed"
]

# 1. Logstash-style parsing
events = []

for line in raw_logs:
    match = re.match(
        r"(\S+ \S+) (\w+) (.*)", line
    )

    if match:
        event = {
            "timestamp": match.group(1),
            "level": match.group(2),
            "message": match.group(3)
        }
        events.append(event)

print("1. Parsed Events:")
for event in events:
    print(event)

# 2. Elasticsearch-style indexing
index = {}

for i, event in enumerate(events, start=1):
    index[i] = event

print("\n2. Indexed Events:", len(index))

# 3. Kibana-style aggregation
counts = Counter(
    event["level"] for event in index.values()
)

print("\n3. Log Dashboard Summary:")
for level, count in sorted(counts.items()):
    print(f"{level}: {count}")

"""**8. Demonstrate Network Segmentation to Block Lateral Movement**"""

# Define network segments
segments = {
    "Guest": ["192.168.1.10"],
    "Employee": ["192.168.2.10"],
    "Sensitive": ["192.168.3.10"]
}

# Define permitted communication paths
access_policy = {
    ("Guest", "Employee"): False,
    ("Guest", "Sensitive"): False,
    ("Employee", "Guest"): False,
    ("Employee", "Sensitive"): False,
    ("Sensitive", "Employee"): True,
    ("Sensitive", "Guest"): False
}

def check_access(source, destination):
    if source == destination:
        return True

    return access_policy.get(
        (source, destination), False
    )


source = "Guest"
destination = "Sensitive"

print("Network Segmentation Simulation")
print("Compromised Segment:", source)
print("Target Segment:", destination)

if check_access(source, destination):
    print("ACCESS GRANTED")
    print("Communication is permitted.")
else:
    print("ACCESS DENIED")
    print("Segmentation blocks lateral movement.")

